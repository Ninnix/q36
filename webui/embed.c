/* Build-time helper: turns the web UI files into a C include for q36-server.
 *
 *   embed OUT.inc WEBUI_DIR FILE...
 *
 * FILE paths are relative to WEBUI_DIR and become URL paths ("js/app.js" is
 * served at "/js/app.js"; "index.html" is also served at "/").  The data is
 * NUL-terminated so the server can treat every asset as a plain C string body. */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

static const char *mime_for(const char *path) {
    const char *dot = strrchr(path, '.');
    if (!dot) return "application/octet-stream";
    if (!strcmp(dot, ".html")) return "text/html; charset=utf-8";
    if (!strcmp(dot, ".css")) return "text/css; charset=utf-8";
    if (!strcmp(dot, ".js")) return "text/javascript; charset=utf-8";
    if (!strcmp(dot, ".svg")) return "image/svg+xml";
    return "application/octet-stream";
}

int main(int argc, char **argv) {
    if (argc < 4) {
        fprintf(stderr, "usage: %s OUT.inc WEBUI_DIR FILE...\n", argv[0]);
        return 2;
    }
    FILE *out = fopen(argv[1], "w");
    if (!out) { perror(argv[1]); return 1; }
    fprintf(out, "/* Generated by webui/embed.c. Do not edit. */\n");

    for (int i = 3; i < argc; i++) {
        char path[4096];
        snprintf(path, sizeof(path), "%s/%s", argv[2], argv[i]);
        FILE *in = fopen(path, "rb");
        if (!in) { perror(path); return 1; }
        fprintf(out, "static const unsigned char webui_data_%d[] = {", i - 3);
        size_t n = 0;
        int c;
        while ((c = fgetc(in)) != EOF) {
            if (n % 16 == 0) fputs("\n", out);
            fprintf(out, "%d,", c);
            n++;
        }
        fputs("0};\n", out);
        fclose(in);
    }

    fputs("static const struct { const char *path, *mime; "
          "const unsigned char *data; size_t len; } webui_assets[] = {\n", out);
    for (int i = 3; i < argc; i++) {
        char path[4096];
        snprintf(path, sizeof(path), "%s/%s", argv[2], argv[i]);
        FILE *in = fopen(path, "rb");
        fseek(in, 0, SEEK_END);
        long len = ftell(in);
        fclose(in);
        if (!strcmp(argv[i], "index.html"))
            fprintf(out, "    {\"/\", \"%s\", webui_data_%d, %ld},\n",
                    mime_for(argv[i]), i - 3, len);
        fprintf(out, "    {\"/%s\", \"%s\", webui_data_%d, %ld},\n",
                argv[i], mime_for(argv[i]), i - 3, len);
    }
    fputs("};\n", out);
    fprintf(out, "#define WEBUI_ASSET_COUNT (sizeof(webui_assets) / sizeof(webui_assets[0]))\n");
    fclose(out);
    return 0;
}
